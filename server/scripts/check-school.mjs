import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import pg from 'pg';
import { databaseOptions } from '../src/config.mjs';
import { schoolRequest as request } from '../src/school.mjs';
const db=new pg.Client(databaseOptions());await db.connect();await db.query('BEGIN');
try {
 const teacher={uid:randomUUID(),name:'Test teacher'},student={uid:randomUUID(),name:'Test student'},extra={uid:randomUUID(),name:'Test extra'},stranger={uid:randomUUID(),name:'Stranger'};
 const call=(who,method,path,body)=>request(db,who,method,'/api/school'+path,body);
 const cls=await call(teacher,'POST','/classes',{name:'Science',subject:'Biology'});
 const other=await call(teacher,'POST','/classes',{name:'Other class'});
 await call(student,'POST','/join',{code:cls.code.toLowerCase()});await call(student,'POST','/join',{code:cls.code});
 await call(extra,'POST','/join',{code:other.code});
 const form={classId:cls.id,title:'Shared task',instructions:'Read chapter one',graded:true,scale:'RAG',minutes:30,addToTasks:true,published:false,extras:[extra.uid]};
 const assignment=await call(teacher,'POST','/assignments',form);
 await call(teacher,'POST',`/assignments/${assignment.id}/edit`,{...form,title:'Edited draft'});
 assert.equal((await call(teacher,'GET','')).assignments.find(a=>a.id===assignment.id).title,'Edited draft');
 assert.equal((await call(student,'GET','')).assignments.length,0);
 await assert.rejects(call(stranger,'POST',`/assignments/${assignment.id}/publish`,{}),e=>e.status===404);
 await call(teacher,'POST',`/assignments/${assignment.id}/publish`,{});
 await assert.rejects(call(teacher,'POST',`/assignments/${assignment.id}/edit`,form),e=>e.status===400);
 assert.equal((await call(student,'GET','')).assignments.length,1);
 assert.equal((await call(extra,'GET','')).assignments.length,1);
 assert.equal((await call(extra,'GET','')).classes.length,1);
 assert.equal((await call(stranger,'GET','')).assignments.length,0);
 await assert.rejects(call(stranger,'POST',`/assignments/${assignment.id}/completion`,{done:true}),e=>e.status===404);
 await assert.rejects(call(student,'GET',`/assignments/${assignment.id}/results`),e=>e.status===404);
 await call(student,'POST',`/assignments/${assignment.id}/completion`,{done:true});
 let roster=(await call(teacher,'GET',`/assignments/${assignment.id}/results`)).students;
 assert.equal(roster.length,2);assert.equal(roster.find(s=>s.id===student.uid).done,true);
 await assert.rejects(call(student,'POST',`/assignments/${assignment.id}/grade`,{studentId:student.uid,grade:'Green'}),e=>e.status===404);
 await assert.rejects(call(teacher,'POST',`/assignments/${assignment.id}/grade`,{studentId:student.uid,grade:'A+'}),e=>e.status===400);
 await call(teacher,'POST',`/assignments/${assignment.id}/grade`,{studentId:student.uid,grade:'Green',feedback:'Well done'});
 assert.equal((await call(student,'GET','')).assignments[0].grade,'Green');
 assert.equal((await call(extra,'GET','')).assignments[0].grade,null);
 await call(student,'POST',`/assignments/${assignment.id}/completion`,{done:false});
 assert.equal((await call(student,'GET','')).assignments[0].grade,'Green');
 await assert.rejects(call(teacher,'POST','/assignments',{...form,extras:[stranger.uid]}),e=>e.status===403);
 await assert.rejects(call(student,'POST','/assignments',form),e=>e.status===403);
 await assert.rejects(call(teacher,'POST','/assignments',{...form,links:[{url:'javascript:alert(1)'}]}),e=>e.status===400);
 console.log('School checks passed: joining, draft privacy, extra recipients, completion, grading and ownership. Test data rolled back.');
} finally {await db.query('ROLLBACK');await db.end();}
